#!/usr/bin/env python3
"""Generate a Gazebo Classic world from a Nav2 occupancy-grid map.

Every occupied cell of the map becomes part of a static box so that the
simulated LiDAR sees exactly the geometry that AMCL and the static costmap
layer expect. Occupied cells are merged into axis-aligned rectangles first,
otherwise a 300x230 map would turn into thousands of tiny boxes.

Usage:
    map_to_world.py <map.yaml> <out.world> [--height 0.5] [--name lab]
"""
import argparse
import os
import sys

import numpy as np
import yaml
from PIL import Image


def load_occupied(map_yaml):
    with open(map_yaml) as f:
        meta = yaml.safe_load(f)
    img_path = os.path.join(os.path.dirname(os.path.abspath(map_yaml)), meta['image'])
    img = np.array(Image.open(img_path).convert('L'), dtype=np.float64)
    occ = (255.0 - img) / 255.0
    if meta.get('negate', 0):
        occ = 1.0 - occ
    occupied = occ > meta['occupied_thresh']
    return occupied, meta


def rectangles(mask):
    """Greedy decomposition of a boolean grid into rectangles of True cells."""
    h, w = mask.shape
    used = np.zeros_like(mask, dtype=bool)
    rects = []
    for r in range(h):
        for c in range(w):
            if not mask[r, c] or used[r, c]:
                continue
            c1 = c
            while c1 + 1 < w and mask[r, c1 + 1] and not used[r, c1 + 1]:
                c1 += 1
            r1 = r
            while r1 + 1 < h and mask[r1 + 1, c:c1 + 1].all() and not used[r1 + 1, c:c1 + 1].any():
                r1 += 1
            used[r:r1 + 1, c:c1 + 1] = True
            rects.append((r, c, r1, c1))
    return rects


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('map_yaml')
    ap.add_argument('out_world')
    ap.add_argument('--height', type=float, default=0.5, help='wall height in metres')
    ap.add_argument('--name', default='lab')
    ap.add_argument('--camera', default=None, metavar='X,Y,Z,PITCH',
                    help='GUI camera pose looking down (default: centre of the map, 11 m up)')
    args = ap.parse_args()

    occupied, meta = load_occupied(args.map_yaml)
    h, w = occupied.shape
    res = float(meta['resolution'])
    ox, oy = float(meta['origin'][0]), float(meta['origin'][1])
    rects = rectangles(occupied)

    cx = ox + w * res / 2.0
    cy = oy + h * res / 2.0
    cz, cpitch = 11.0, 1.45
    if args.camera:
        cx, cy, cz, cpitch = (float(v) for v in args.camera.split(','))
    hz = args.height

    boxes = []
    for i, (r0, c0, r1, c1) in enumerate(rects):
        sx = (c1 - c0 + 1) * res
        sy = (r1 - r0 + 1) * res
        x = ox + (c0 + c1 + 1) * res / 2.0
        y = oy + (h - (r0 + r1 + 1) / 2.0) * res
        boxes.append(f"""      <collision name="c{i}">
        <pose>{x:.4f} {y:.4f} {hz / 2:.3f} 0 0 0</pose>
        <geometry><box><size>{sx:.4f} {sy:.4f} {hz:.3f}</size></box></geometry>
      </collision>
      <visual name="v{i}">
        <pose>{x:.4f} {y:.4f} {hz / 2:.3f} 0 0 0</pose>
        <geometry><box><size>{sx:.4f} {sy:.4f} {hz:.3f}</size></box></geometry>
        <material><script><uri>file://media/materials/scripts/gazebo.material</uri><name>Gazebo/Grey</name></script></material>
      </visual>""")

    world = f"""<?xml version="1.0"?>
<!-- Generated by scripts/map_to_world.py from {os.path.basename(args.map_yaml)}
     ({w}x{h} cells at {res} m, origin [{ox}, {oy}]): {len(rects)} boxes from
     {int(occupied.sum())} occupied cells. Do not edit by hand; regenerate instead. -->
<sdf version="1.6">
  <world name="{args.name}">
    <include><uri>model://ground_plane</uri></include>
    <include><uri>model://sun</uri></include>
    <scene><shadows>false</shadows></scene>

    <gui fullscreen="0">
      <camera name="user_camera">
        <pose>{cx:.2f} {cy:.2f} {cz:.2f} 0 {cpitch:.3f} 1.5708</pose>
        <view_controller>orbit</view_controller>
      </camera>
    </gui>

    <physics type="ode">
      <real_time_update_rate>1000.0</real_time_update_rate>
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1</real_time_factor>
      <ode>
        <solver><type>quick</type><iters>150</iters><sor>1.4</sor></solver>
        <constraints><cfm>0.00001</cfm><erp>0.2</erp>
          <contact_max_correcting_vel>2000.0</contact_max_correcting_vel>
          <contact_surface_layer>0.01</contact_surface_layer></constraints>
      </ode>
    </physics>

    <!-- Lets ROS nodes move models with /gazebo/set_entity_state (used by the moving obstacle). -->
    <plugin name="gazebo_ros_state" filename="libgazebo_ros_state.so">
      <ros><namespace>/gazebo</namespace></ros>
      <update_rate>10.0</update_rate>
    </plugin>

    <model name="{args.name}_walls">
      <static>true</static>
      <pose>0 0 0 0 0 0</pose>
      <link name="link">
{chr(10).join(boxes)}
      </link>
    </model>
  </world>
</sdf>
"""
    with open(args.out_world, 'w') as f:
        f.write(world)
    print(f"{args.out_world}: {len(rects)} boxes from {int(occupied.sum())} occupied cells "
          f"({w}x{h} @ {res} m, origin {ox},{oy}; map spans x[{ox:.2f},{ox + w * res:.2f}] y[{oy:.2f},{oy + h * res:.2f}])")


if __name__ == '__main__':
    sys.exit(main())
